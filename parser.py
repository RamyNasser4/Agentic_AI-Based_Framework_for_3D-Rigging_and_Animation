import json
from typing import Any, Dict, List, Tuple


class RigDataParser:
    def __init__(self, text: str) -> None:
        self.text = text
        self.pos = 0
        self.length = len(text)

    def parse(self) -> Dict[str, Any]:
        self._skip_ws()
        data = self._parse_node(allow_sibling_boundary=False)
        self._skip_ws()
        if self.pos != self.length:
            raise ValueError(f"Unexpected trailing content at index {self.pos}: {self.text[self.pos:self.pos + 40]!r}")
        return data

    def _parse_node(self, allow_sibling_boundary: bool) -> Dict[str, Any]:
        node: Dict[str, Any] = {}

        while True:
            self._skip_ws()
            key = self._parse_key()
            self._expect(":")
            node[key] = self._parse_value(key)
            self._skip_ws()

            if self._at_end() or self._peek() == "]":
                break
            if self._peek() != ",":
                raise ValueError(f"Expected ',' or ']' at index {self.pos}, got {self._peek()!r}")

            comma_pos = self.pos
            self.pos += 1
            self._skip_ws()

            if allow_sibling_boundary and "name" in node and self._next_key_is("name"):
                self.pos = comma_pos
                break

        return node

    def _parse_value(self, key: str):
        self._skip_ws()
        if key in {"position", "rotation"}:
            return self._parse_number_tuple()
        if key == "children":
            return self._parse_children_list()
        return self._parse_scalar()

    def _parse_children_list(self) -> List[Dict[str, Any]]:
        self._expect("[")
        self._skip_ws()

        children: List[Dict[str, Any]] = []
        if self._consume_if("]"):
            return children

        while True:
            child = self._parse_node(allow_sibling_boundary=True)
            children.append(child)
            self._skip_ws()

            if self._consume_if("]"):
                break
            self._expect(",")
            self._skip_ws()

        return children

    def _parse_number_tuple(self) -> Tuple[float, ...]:
        self._expect("(")
        values: List[float] = []

        while True:
            self._skip_ws()
            values.append(self._parse_number())
            self._skip_ws()

            if self._consume_if(")"):
                break
            self._expect(",")

        return tuple(values)

    def _parse_number(self) -> float:
        self._skip_ws()
        start = self.pos
        while not self._at_end() and self._peek() not in ",)":
            self.pos += 1

        raw = self.text[start:self.pos].strip()
        if not raw:
            raise ValueError(f"Expected number at index {start}")

        try:
            return float(raw)
        except ValueError as exc:
            raise ValueError(f"Invalid numeric value {raw!r} at index {start}") from exc

    def _parse_scalar(self) -> str:
        start = self.pos
        while not self._at_end() and self._peek() not in ",]":
            self.pos += 1

        token = self.text[start:self.pos].strip()
        if not token:
            raise ValueError(f"Expected scalar token at index {start}")
        return token

    def _parse_key(self) -> str:
        self._skip_ws()
        start = self.pos
        while not self._at_end() and self._peek() not in ":,[]()":
            self.pos += 1

        key = self.text[start:self.pos].strip()
        if not key:
            raise ValueError(f"Expected key at index {start}")
        if self._at_end() or self._peek() != ":":
            raise ValueError(f"Expected ':' after key {key!r} at index {self.pos}")
        return key

    def _next_key_is(self, expected_key: str) -> bool:
        saved_pos = self.pos
        try:
            self._skip_ws()
            start = self.pos
            while not self._at_end() and self._peek() not in ":,[]()":
                self.pos += 1

            if self._at_end() or self._peek() != ":":
                return False
            return self.text[start:self.pos].strip() == expected_key
        finally:
            self.pos = saved_pos

    def _expect(self, ch: str) -> None:
        self._skip_ws()
        if self._at_end() or self.text[self.pos] != ch:
            actual = self.text[self.pos] if not self._at_end() else "<eof>"
            raise ValueError(f"Expected {ch!r} at index {self.pos}, got {actual!r}")
        self.pos += 1

    def _consume_if(self, ch: str) -> bool:
        self._skip_ws()
        if not self._at_end() and self.text[self.pos] == ch:
            self.pos += 1
            return True
        return False

    def _skip_ws(self) -> None:
        while not self._at_end() and self.text[self.pos].isspace():
            self.pos += 1

    def _peek(self) -> str:
        return self.text[self.pos]

    def _at_end(self) -> bool:
        return self.pos >= self.length


def parse_rig_data(raw_rig_data: str) -> Dict[str, Any]:
    return RigDataParser(raw_rig_data).parse()


